import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectDirectory = path.resolve(scriptDirectory, '..');
const iconDirectory = path.join(projectDirectory, 'assets/icons/categories');
const registryPath = path.join(projectDirectory, 'components/categoryIconRegistry.generated.ts');
const galleryPath = path.join(projectDirectory, 'assets/icons/gallery.html');
const checkOnly = process.argv.includes('--check');

const filenames = (await readdir(iconDirectory))
  .filter((filename) => /^ic-[a-z0-9]+\.svg$/.test(filename))
  .sort((a, b) => a.localeCompare(b));

if (filenames.length === 0) {
  throw new Error(`No category SVGs found in ${iconDirectory}`);
}

const icons = await Promise.all(
  filenames.map(async (filename) => {
    const id = filename.slice(3, -4);
    const source = (await readFile(path.join(iconDirectory, filename), 'utf8')).trim();
    validateIcon(id, source);
    return { id, source };
  }),
);

const iconsBySource = new Map();
for (const icon of icons) {
  const group = iconsBySource.get(icon.source) ?? [];
  group.push(icon);
  iconsBySource.set(icon.source, group);
}
const duplicateSourceGroups = [...iconsBySource.values()].filter((group) => group.length > 1);

if (duplicateSourceGroups.length > 0) {
  const duplicates = duplicateSourceGroups
    .map((group) => group.map(({ id }) => id).join(', '))
    .join('; ');
  throw new Error(`Duplicate category artwork found: ${duplicates}`);
}

const registry = buildRegistry(icons);
const gallery = buildGallery(icons);

if (checkOnly) {
  const mismatches = [];
  if ((await readFile(registryPath, 'utf8')) !== registry) mismatches.push(relative(registryPath));
  if ((await readFile(galleryPath, 'utf8')) !== gallery) mismatches.push(relative(galleryPath));
  if (mismatches.length > 0) {
    throw new Error(`Generated icon files are stale: ${mismatches.join(', ')}. Run npm run icons:generate.`);
  }
  console.log(`Category icon registry is current (${icons.length} individual SVGs).`);
} else {
  await Promise.all([
    writeFile(registryPath, registry),
    writeFile(galleryPath, gallery),
  ]);
  console.log(`Generated ${icons.length} category icons.`);
}

function relative(filename) {
  return path.relative(projectDirectory, filename);
}

function validateIcon(id, source) {
  const requirements = [
    ['24×24 viewBox', 'viewBox="0 0 24 24"'],
    ['no fill', 'fill="none"'],
    ['canonical ink', 'stroke="#1A1A1A"'],
    ['1.7px stroke', 'stroke-width="1.7"'],
    ['rounded joins', 'stroke-linejoin="round"'],
    ['rounded caps', 'stroke-linecap="round"'],
    ['mint accent', '#3ECDA5'],
  ];

  for (const [label, fragment] of requirements) {
    if (!source.includes(fragment)) {
      throw new Error(`Icon “${id}” is missing ${label}.`);
    }
  }

  if (!source.startsWith('<svg ') || !source.endsWith('</svg>')) {
    throw new Error(`Icon “${id}” is not a complete SVG.`);
  }
}

function buildRegistry(iconList) {
  const rows = iconList
    .map(({ id, source }) => `  ${JSON.stringify(id)}: ${JSON.stringify(source)},`)
    .join('\n');

  return `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-category-icons.mjs.
// Edit assets/icons/categories/ic-*.svg, then run npm run icons:generate.

export const CATEGORY_ICON_XML = {
${rows}
} as const;

export type CategoryIconId = keyof typeof CATEGORY_ICON_XML;

export const CATEGORY_ICON_IDS = Object.freeze(
  Object.keys(CATEGORY_ICON_XML) as CategoryIconId[],
);

export function hasCategoryIcon(id?: string | null): id is CategoryIconId {
  return Boolean(id && Object.prototype.hasOwnProperty.call(CATEGORY_ICON_XML, id));
}
`;
}

function buildGallery(iconList) {
  const cards = iconList
    .map(({ id, source }) => {
      const idleSource = source.replaceAll('#1A1A1A', '#858B88');
      const selectedSource = source.replaceAll('#1A1A1A', '#181A19');
      return `      <figure data-icon="${id}">
        <div class="states">
          <div class="icon-circle">${idleSource}</div>
          <div class="icon-circle selected">${selectedSource}</div>
        </div>
        <figcaption>${id}</figcaption>
      </figure>`;
    })
    .join('\n');

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <title>RICH category icon audit</title>
    <style>
      :root { color-scheme: light; font-family: -apple-system, BlinkMacSystemFont, "PingFang SC", sans-serif; }
      * { box-sizing: border-box; }
      body { margin: 0; background: #f3f5f4; color: #181a19; }
      header { position: sticky; top: 0; z-index: 2; padding: 20px 24px 16px; background: rgba(255,255,255,.94); border-bottom: 1px solid #e6e9e7; backdrop-filter: blur(16px); }
      h1 { margin: 0 0 5px; font-size: 20px; letter-spacing: -.02em; }
      p { margin: 0; color: #6f7572; font-size: 13px; }
      main { display: grid; grid-template-columns: repeat(auto-fill, minmax(138px, 1fr)); gap: 10px; padding: 18px; }
      figure { margin: 0; padding: 16px 10px 12px; text-align: center; background: white; border: 1px solid #ecefed; border-radius: 16px; }
      .states { display: flex; align-items: center; justify-content: center; gap: 10px; }
      .icon-circle { width: 46px; height: 46px; display: grid; place-items: center; border-radius: 50%; background: #f7f8f7; }
      .icon-circle.selected { background: white; border: 2px solid #181a19; }
      svg { width: 25px; height: 25px; }
      figcaption { margin-top: 9px; color: #555b58; font: 11px/1.2 ui-monospace, SFMono-Regular, Menlo, monospace; }
    </style>
  </head>
  <body>
    <header>
      <h1>RICH category icons</h1>
      <p>${iconList.length} independently drawn 24×24 SVGs · idle and selected at the in-app 25px size</p>
    </header>
    <main>
${cards}
    </main>
  </body>
</html>
`;
}
