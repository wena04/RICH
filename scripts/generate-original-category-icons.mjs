import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = path.join(repoRoot, 'src/domain/originalCategoryCatalog.json');
const imageDirectory = path.join(repoRoot, 'assets/images/category-original');
const outputPath = path.join(repoRoot, 'components/originalCategoryIconRegistry.generated.ts');

const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
const nameEntries = catalog.flatMap((section) =>
  section.typeItems.map((item) => [item.name, item.iconName]),
);

const aliases = {
  工资: 'icon_gongzixinshui',
  兼职: 'icon_jianzhiwaikuai',
  理财: 'icon_touzilicai',
  退款: 'icon_tuikuanfankuan',
  其他收入: 'icon_qitashouyi',
  还钱: 'icon_huankuan',
  '人情/借钱': 'icon_renqing',
  校园餐饮: 'icon_sancan',
  聚餐: 'icon_juhui',
  公交地铁: 'icon_ditie',
  汽车加油: 'icon_qichejiayou',
  油费: 'icon_qichejiayou',
  水电网: 'icon_shuidianmei',
  看诊: 'icon_jiuzhen',
  健身: 'icon_yundong',
  住宿: 'icon_jiudian',
  活动门票: 'icon_jingqumenpiao',
  学费: 'icon_peixun',
  管理分类: 'icon_setting',
};

const images = readdirSync(imageDirectory)
  .filter((filename) => /^icon_[a-z0-9]+\.png$/.test(filename))
  .map((filename) => filename.slice(0, -4))
  .sort();

const imageLines = images.map(
  (iconName) => `  ${JSON.stringify(iconName)}: require('../assets/images/category-original/${iconName}.png'),`,
);
const nameLines = [...new Map([...nameEntries, ...Object.entries(aliases)])]
  .sort(([left], [right]) => left.localeCompare(right, 'zh-CN'))
  .map(([name, iconName]) => `  ${JSON.stringify(name)}: ${JSON.stringify(iconName)},`);

const source = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-original-category-icons.mjs.
// The PNG files and category mapping come from the supplied RichNote app bundle.

import type { ImageSourcePropType } from 'react-native';

export const ORIGINAL_CATEGORY_ICON_IMAGES = {
${imageLines.join('\n')}
} as const satisfies Record<string, ImageSourcePropType>;

export type OriginalCategoryIconName = keyof typeof ORIGINAL_CATEGORY_ICON_IMAGES;

export const ORIGINAL_ICON_NAME_BY_CATEGORY = {
${nameLines.join('\n')}
} as const satisfies Record<string, OriginalCategoryIconName>;

export function originalIconNameForCategory(name?: string | null): OriginalCategoryIconName | null {
  const normalizedName = name?.trim();
  if (!normalizedName) return null;
  return ORIGINAL_ICON_NAME_BY_CATEGORY[normalizedName as keyof typeof ORIGINAL_ICON_NAME_BY_CATEGORY] ?? null;
}

export function hasOriginalCategoryIcon(id?: string | null): id is OriginalCategoryIconName {
  return Boolean(id && Object.prototype.hasOwnProperty.call(ORIGINAL_CATEGORY_ICON_IMAGES, id));
}
`;

writeFileSync(outputPath, source);
