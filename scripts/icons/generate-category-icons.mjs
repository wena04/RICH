// Builds the category icon registry from assets/icons/categories/icon_*.svg.
//
// Outputs:
//   components/icons/categoryArt.generated.ts   SVG markup by icon name (rendered by CategoryIcon)
//   src/domain/categoryIcons/names.generated.ts the list of valid icon names (domain layer)
//   assets/icons/gallery.html                   visual QA sheet: idle, dimmed and selected states
//
// Usage: npm run icons:generate   (or npm run icons:check to fail when outputs are stale)
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const projectDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const iconDirectory = path.join(projectDirectory, 'assets/icons/categories');
const artPath = path.join(projectDirectory, 'components/icons/categoryArt.generated.ts');
const namesPath = path.join(projectDirectory, 'src/domain/categoryIcons/names.generated.ts');
const galleryPath = path.join(projectDirectory, 'assets/icons/gallery.html');
const checkOnly = process.argv.includes('--check');

const INK = '#000000';
const ACCENT = '#02B17B';

const filenames = (await readdir(iconDirectory)).filter((f) => /^icon_[a-z0-9]+\.svg$/.test(f)).sort();
if (filenames.length === 0) throw new Error(`No category SVGs found in ${iconDirectory}`);

const icons = await Promise.all(
  filenames.map(async (filename) => {
    const name = filename.slice(0, -4);
    const source = (await readFile(path.join(iconDirectory, filename), 'utf8')).trim();
    validate(name, source);
    return { name, source };
  }),
);

const outputs = [
  [artPath, buildArt(icons)],
  [namesPath, buildNames(icons)],
  [galleryPath, buildGallery(icons)],
];

if (checkOnly) {
  const stale = [];
  for (const [file, contents] of outputs) {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current !== contents) stale.push(path.relative(projectDirectory, file));
  }
  if (stale.length) throw new Error(`Generated icon files are stale: ${stale.join(', ')}. Run npm run icons:generate.`);
  console.log(`Category icon registry is current (${icons.length} icons).`);
} else {
  await Promise.all(outputs.map(([file, contents]) => writeFile(file, contents)));
  console.log(`Generated ${icons.length} category icons.`);
}

function validate(name, source) {
  if (!source.startsWith('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48">') || !source.endsWith('</svg>')) {
    throw new Error(`Icon "${name}" must be a complete SVG on the 48-unit viewBox.`);
  }
  // Glyph only: the #F7F7F7 disc is drawn by the caller, so the art may use just the two original
  // inks, as fills (traced originals) or strokes (redrawn glyphs, <desc>redrawn</desc>).
  const paints = [...source.matchAll(/(?:fill|stroke)="([^"]+)"/g)]
    .map((m) => m[1].toUpperCase())
    .filter((paint) => paint !== 'NONE');
  const unexpected = paints.filter((paint) => paint !== INK && paint !== ACCENT);
  if (!paints.includes(INK) || unexpected.length) {
    throw new Error(`Icon "${name}" must use only ${INK} and ${ACCENT} (found ${[...new Set(paints)].join(', ')}).`);
  }
  if (/<image|<circle[^>]*fill="#F7F7F7"/i.test(source)) {
    throw new Error(`Icon "${name}" must be glyph shapes without a background disc.`);
  }
}

function buildArt(list) {
  const rows = list.map(({ name, source }) => `  ${name}: ${JSON.stringify(source)},`).join('\n');
  return `/* eslint-disable */
// AUTO-GENERATED by scripts/icons/generate-category-icons.mjs.
// Edit assets/icons/categories/icon_*.svg, then run npm run icons:generate.

import type { CategoryIconName } from '@/src/domain/categoryIcons/names.generated';

/** Original Rich 1.1.0 category glyphs, without their #F7F7F7 disc. */
export const CATEGORY_ART_XML: Record<CategoryIconName, string> = {
${rows}
};

export const CATEGORY_ART_INK = ${JSON.stringify(INK)};
export const CATEGORY_ART_ACCENT = ${JSON.stringify(ACCENT)};
`;
}

function buildNames(list) {
  const rows = list.map(({ name }) => `  ${JSON.stringify(name)},`).join('\n');
  return `/* eslint-disable */
// AUTO-GENERATED by scripts/icons/generate-category-icons.mjs from assets/icons/categories/.

export const CATEGORY_ICON_NAMES = [
${rows}
] as const;

export type CategoryIconName = (typeof CATEGORY_ICON_NAMES)[number];

const NAME_SET: ReadonlySet<string> = new Set(CATEGORY_ICON_NAMES);

export function isCategoryIconName(value?: string | null): value is CategoryIconName {
  return Boolean(value && NAME_SET.has(value));
}
`;
}

function buildGallery(list) {
  const cards = list
    .map(({ name, source }) => `      <figure>
        <div class="states">
          <div class="disc">${source}</div>
          <div class="disc dimmed">${source}</div>
          <div class="disc selected">${source}</div>
        </div>
        <figcaption>${name}</figcaption>
      </figure>`)
    .join('\n');
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <title>RICH category icons</title>
    <style>
      :root { font-family: -apple-system, BlinkMacSystemFont, "PingFang SC", sans-serif; }
      body { margin: 0; background: #fff; color: #000; }
      header { position: sticky; top: 0; padding: 18px 22px 14px; background: rgba(255,255,255,.95); border-bottom: 1px solid #eaeaea; }
      h1 { margin: 0 0 4px; font-size: 18px; }
      p { margin: 0; color: #777; font-size: 12px; }
      main { display: grid; grid-template-columns: repeat(auto-fill, minmax(190px, 1fr)); gap: 8px; padding: 16px; }
      figure { margin: 0; padding: 12px 8px 10px; text-align: center; border: 1px solid #f0f0f0; }
      .states { display: flex; justify-content: center; gap: 8px; }
      .disc { width: 48px; height: 48px; border-radius: 50%; background: #F7F7F7; box-sizing: border-box; }
      .disc svg { width: 48px; height: 48px; display: block; }
      .dimmed { opacity: .5; }
      .selected { box-shadow: inset 0 0 0 1.7px #000; }
      figcaption { margin-top: 8px; color: #555; font: 11px ui-monospace, Menlo, monospace; }
    </style>
  </head>
  <body>
    <header>
      <h1>RICH category icons</h1>
      <p>${list.length} original glyphs (vector), drawn over the 48pt #F7F7F7 disc · idle · dimmed (another category selected) · selected</p>
    </header>
    <main>
${cards}
    </main>
  </body>
</html>
`;
}
